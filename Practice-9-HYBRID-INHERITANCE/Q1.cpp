// Hybrid Inheritance
// Placement Definition

// Hybrid Inheritance is a combination of two or more types of inheritance.

// Simple language me:

// Jab ek hi program me multiple inheritance types combine ho jayein, use Hybrid Inheritance kehte hain.

// Example
//            Person
//           /      \
//      Employee    Student
//           \      /
//       TeachingAssistant

// Is diagram me:

// Part 1
// Person
//    │
// Employee

// Ye Single Inheritance hai.

// Part 2
// Person
//    │
// Student

// Ye bhi Single Inheritance hai.

// Part 3
// Employee    Student
//       \      /
//    TeachingAssistant

// Ye Multiple Inheritance hai.

// Final

// Program me:

// Single Inheritance ✅
// Multiple Inheritance ✅

// Dono combine hue.

// 👉 Isliye ye Hybrid Inheritance hai.

// Rule (Interview)

// Hybrid Inheritance = Combination of two or more inheritance types.

// Ye definition yaad rakhna.

// Difference
// Multiple Inheritance
// A       B
//  \     /
//    \  /
//     C

// Sirf Multiple Inheritance.

// Hybrid Inheritance
//       A
//      / \
//     B   C
//      \ /
//       D

// Yahan:

// A → B = Single
// A → C = Single
// B + C → D = Multiple

// Isliye ye Hybrid hai.

// 🎯 Interview Trap

// Interviewer:

// Is every Diamond Structure a Hybrid Inheritance?

// Answer

// ✅ Yes.

// Because Diamond structure me:

// Single Inheritance hoti hai.
// Multiple Inheritance hoti hai.

// Dono milkar Hybrid banate hain.

