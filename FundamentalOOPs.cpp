// Drawback of Functional programming: 
    // 1) does not model real world problem very well.
    // 2) if a new data is added, all the functions needs to be modified to accesss the Data,
    // 3) Global data is accessible to all the functions(that data which is not for irrelevent function).
    // 4) No clear boundaries and well definition of code.
    // 5) No Modularity: functional programs can become monolithic and difficult to maintain as they grow in complexity.


// Class is blueprint or template like Car
// Object is real world actual entity like Scorpio, Verna, Amaze etc.
// Object us actual blueprint ya template ko possess krne wala koi entity hai.
// Object is instance of a Class.

// Class:
    // A class is a blueprint or template for creating objects.
    // It defines the data (variables) and functions (methods) that objects will have.
    // No memory is allocated when a class is created.

// Object:
    // An object is an instance of a class.
    // It is created from a class.
    // Memory is allocated when an object is created.
    // Objects can access the data and functions of the class.

// Attributes and Behaviour:
    // Attributes are state, properties of an object.
    // Behaviour is methods/functions that an object can perform.

// Attributes (Properties / Data Members / Varibles)
    // Attributes are the characteristics or data of an object.
    // They describe what an object has.
    // In C++, attributes are represented by variables inside a class.

    // Example:

    // class Student {
    // public:
    //     string name;   // Attribute
    //     int age;       // Attribute
    // };

    // Here:

    // name and age are attributes of the Student class.


// Behavior (Methods / Member Functions)
    // Behavior represents the actions an object can perform.
    // It describes what an object does.
    // In C++, behavior is represented by functions inside a class.

    // Example:

    // class Student {
    // public:
    //     string name;

    //     void study() {   // Behavior
    //         cout << "Studying";
    //     }
    // };

    // Here:

    // study() is a behavior of the Student class.

