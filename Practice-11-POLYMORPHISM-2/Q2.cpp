// 📂 Operator Overloading

// Sabse pehle concept.

// Normal operator:

// 5 + 10

// + kya karta hai?

// Addition.

// Lekin agar hamare paas object ho:

// Complex c1, c2;

// Aur hum likhen:

// c1 + c2;

// Compiler bolega:

// "Bhai, mujhe nahi pata do Complex objects ko add kaise karna hai."

// Isliye hum compiler ko sikhate hain.

// Is process ko Operator Overloading kehte hain.

// Real Life Example

// Normal:

// 10 + 20

// Output:

// 30

// Object:

// Student s1;
// Student s2;

// s1 + s2;

// Compiler:

// Error 😵

// Kyun?

// + operator ko sirf numbers ka behavior pata hai.

// Objects ka nahi.

// Hum uska behavior define karte hain.



